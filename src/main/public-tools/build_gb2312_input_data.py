def generate() -> str:
    bitmap = bytearray((87 * 94 + 7) // 8)
    count = 0
    for row in range(87):
        for col in range(94):
            pair = bytes((0xA1 + row, 0xA1 + col))
            try:
                pair.decode("gb2312")
            except UnicodeDecodeError:
                continue
            position = row * 94 + col
            bitmap[position // 8] |= 1 << (position % 8)
            count += 1
    if count != 7445:
        raise ValueError(f"Expected 7445 GB2312 positions, found {count}")
    lines = ["/* Generated by tools/build_gb2312_input_data.py. */",
             "static const unsigned char gb_valid[] = {"]
    for at in range(0, len(bitmap), 16):
        lines.append("    " + ",".join(f"0x{x:02X}" for x in bitmap[at:at + 16]) + ",")
    lines += ["};", "", "typedef struct { const char *key; const char *candidates; } PYENTRY;",
              "static const PYENTRY py_table[] = {"]
    for key, chars in sorted(PINYIN.items()):
        encoded = chars.encode("gb2312")
        escaped = "".join(f"\\x{x:02X}" for x in encoded)
        lines.append(f'    {{"{key}", "{escaped}"}},')
    lines += ["};", ""]
    return "\n".join(lines)


