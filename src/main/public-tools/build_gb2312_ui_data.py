"""Generate GB2312 byte string literals for Win16 Chinese interface labels."""

from __future__ import annotations

# Project paths after the src/main + src/test directory reorganization.
import sys as _layout_sys
from pathlib import Path as _LayoutPath
_LAYOUT_ROOT = next(p for p in _LayoutPath(__file__).resolve().parents
                    if (p / "src/main").is_dir() and (p / "release").is_dir())
_layout_sys.path[:0] = [str(_LAYOUT_ROOT / p) for p in (
    "src/main/native-gb2312", "src/main/public-tools", "src/main/cga-driver",
    "src/main/install", "src/main/install/windows", "src/test/install")]


from pathlib import Path


ROOT = _LAYOUT_ROOT
STRINGS = {
    "gb_ui_header": "简体中文编辑器",
    "gb_ui_actions": "F1英文/拼音 F2区位 F3保存 F4读取",
    "gb_ui_pinyin": "拼音：",
    "gb_ui_quwei": "区位码（行01-87，列01-94）：",
    "gb_ui_ascii": "英文输入",
    "gb_ui_note": "区位码可输入全部GB2312字符",
    "gb_ui_ready": "拼音输入：空格或数字选字",
    "gb_ui_full": "文本已满",
    "gb_ui_unknown": "拼音无匹配，请用区位码",
    "gb_ui_nochoice": "候选号无效",
    "gb_ui_committed": "汉字已输入",
    "gb_ui_badquwei": "区位码未分配",
    "gb_ui_quwei_done": "区位码输入完成",
    "gb_ui_quwei_enter": "请输入四位区位码",
    "gb_ui_pinyin_mode": "拼音输入",
    "gb_ui_save_done": "已保存C:\\GBNOTE.TXT",
    "gb_ui_load_done": "已读取C:\\GBNOTE.TXT",
    "gb_ui_save_fail": "保存失败",
    "gb_ui_load_fail": "读取失败",
    "gb_ui_file_large": "文件超过本编辑器容量",
    "gb_ui_file_invalid": "不是单行GB2312文本",
}


def generate() -> str:
    lines = ["/* Generated by tools/build_gb2312_ui_data.py. */"]
    for name, value in STRINGS.items():
        codes = ",".join(f"0x{x:02X}" for x in value.encode("gb2312"))
        lines.append(f"static const char {name}[] = {{{codes},0}};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    path = ROOT / "src/test/native-gb2312/gb2312_first/GBUI.H"
    path.write_text(generate(), encoding="ascii")
    print(path)
