def main() -> None:
    target = _LAYOUT_ROOT / "src/test/native-gb2312/gb2312_first/GBMENU.H"
    rows = ["/* Generated by tools/build_gb2312_menu_ui.py. */",
            "typedef struct { const char *english; const char *chinese; } GBMENULABEL;",
            "static GBMENULABEL gb_menu_labels[] = {"]
    for english, chinese in sorted(LABELS, key=lambda pair: pair[0].upper()):
        encoded = "".join(f"\\x{byte:02X}" for byte in chinese.encode("gb2312"))
        rows.append(f'    {{"{english}", "{encoded}"}},')
    rows += ["};", "#define GB_MENU_LABEL_COUNT " + str(len(LABELS)), ""]
    rows.append("static GBMENULABEL gb_title_labels[] = {")
    for english, chinese in TITLES:
        encoded = "".join(f"\\x{byte:02X}" for byte in chinese.encode("gb2312"))
        rows.append(f'    {{"{english}", "{encoded}"}},')
    rows += ["};", "#define GB_TITLE_LABEL_COUNT " + str(len(TITLES)), ""]
    target.write_text("\n".join(rows), encoding="ascii")
    print(target)


if __name__ == "__main__":
    main()
